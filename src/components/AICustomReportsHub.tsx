import React, { useState } from 'react';
import { Bot, FileText, Download, Sparkles, Filter, CheckCircle2, BarChart3, Layers, Database, ArrowRight } from 'lucide-react';
import jsPDF from 'jspdf';
import 'jspdf-autotable';

interface AICustomReportsHubProps {
  lang: 'ar' | 'en' | 'es' | 'fr';
}

export const AICustomReportsHub: React.FC<AICustomReportsHubProps> = ({ lang }) => {
  const [prompt, setPrompt] = useState('');
  const [selectedModule, setSelectedModule] = useState('all');
  const [isGenerating, setIsGenerating] = useState(false);
  const [generatedReport, setGeneratedReport] = useState<{
    title: string;
    summary: string;
    headers: string[];
    rows: string[][];
  } | null>({
    title: 'تقرير تحليل الأداء الشامل والمالي لمحطة الفرز والتعبئة',
    summary: 'تم توليد هذا التقرير بناءً على بيانات الـ ERP والـ PLC لخطوط الفرز والتصدير والمالية لشهر أكتوبر 2026.',
    headers: ['القسم / القطع', 'إجمالي المعاملات', 'الكفاءة التشغيلية %', 'صافي العائد (EGP)', 'الحالة'],
    rows: [
      ['خط الفرز والتحجيم البصري (Line 1)', '142 تشغيلة', '94.2%', '1,250,000 EGP', 'ممتاز'],
      ['قسم غرف التبريد والتحكم (Cold Storage)', '38 غرفة', '98.5%', '485,000 EGP', 'مستقر'],
      ['شحنات التصدير الدولية (Export)', '12 حاوية', '96.0%', '3,420,000 EGP', 'جاهز'],
      ['الإدارة المالية والمرتبات', '48 قيد', '100%', '845,000 EGP (مصروفات)', 'منتظم']
    ]
  });

  const isAr = lang === 'ar';

  const handleAiGenerate = (e: React.FormEvent) => {
    e.preventDefault();
    if (!prompt) return;

    setIsGenerating(true);
    setTimeout(() => {
      setGeneratedReport({
        title: `تقرير مخصص بناءً على طلب المستخدم: "${prompt}"`,
        summary: `تم إعداد وتحليل هذا التقرير ذابياً بواسطة المساعد الذكي لـ Falcon Eye OS وفقاً للبيانات الحية لجميع أقسام المحطة.`,
        headers: ['مؤشر الأداء (Metric)', 'القيمة الحالية', 'المعدل المستهدف', 'تقييم الذكاء الاصطناعي'],
        rows: [
          ['معدل الكفاءة التشغيلية للخطوط', '94.8%', '90.0%', 'ممتاز (يتجاوز المستهدف)'],
          ['نسبة الفرز والفاقد المسموح', '2.8%', '< 3.5%', 'مطابق لمعايير التصدير'],
          ['استهلاك الطاقة لمولدات الطوارئ', '42 kW/h', '50 kW/h', 'استهلاك اقتصادي'],
          ['سرعة استجابة حسابت الـ PLC', '12 ms', '< 20 ms', 'زمن استجابة فائق السرعة']
        ]
      });
      setIsGenerating(false);
      setPrompt('');
    }, 1500);
  };

  const downloadPDF = () => {
    if (!generatedReport) return;
    const doc = new jsPDF();
    doc.setFillColor(15, 23, 42);
    doc.rect(0, 0, 210, 35, 'F');
    doc.setTextColor(255, 255, 255);
    doc.setFontSize(16);
    doc.text('FALCON EYE AI CUSTOM REPORT STUDIO', 14, 18);
    doc.setFontSize(10);
    doc.setTextColor(52, 211, 153);
    doc.text(`Generated by AI Assistant | Date: ${new Date().toISOString().split('T')[0]}`, 14, 27);

    doc.setTextColor(30, 41, 59);
    doc.setFontSize(14);
    doc.text(generatedReport.title, 14, 48);

    doc.setFontSize(10);
    doc.setTextColor(100, 116, 139);
    doc.text(generatedReport.summary, 14, 56);

    (doc as any).autoTable({
      startY: 65,
      head: [generatedReport.headers],
      body: generatedReport.rows,
      theme: 'grid',
      headStyles: { fillColor: [15, 23, 42], textColor: [255, 255, 255] }
    });

    doc.save(`FalconEye_Custom_AI_Report_${Date.now()}.pdf`);
  };

  return (
    <div className="space-y-6 animate-fadeIn max-w-7xl mx-auto py-4">
      {/* Header Banner */}
      <div className="bg-gradient-to-r from-slate-950 via-teal-950 to-slate-900 rounded-2xl p-6 sm:p-8 text-white shadow-xl border border-slate-700/60 flex flex-col md:flex-row items-start md:items-center justify-between gap-6">
        <div>
          <div className="flex items-center gap-2 mb-2">
            <span className="px-2.5 py-0.5 rounded-full text-[10px] font-bold bg-emerald-500/20 text-emerald-300 border border-emerald-500/30 flex items-center gap-1.5">
              <Sparkles className="w-3 h-3" /> AI Custom Reporting Engine
            </span>
          </div>
          <h1 className="text-xl sm:text-2xl font-black tracking-tight">
            {isAr ? 'نظام التقارير الذكية المخصصة بواسطة المساعد الذكي' : 'AI-Powered Custom Report Generator & Analytics'}
          </h1>
          <p className="text-xs sm:text-sm text-slate-300 mt-1 max-w-3xl">
            {isAr ? 'اطلب أي تقرير تريده بالطبيعة الحرة (باللغة العربية أو الإنجليزية)، وسيقوم المساعد الذكي بتحليل البيانات، إنشاء الجداول، وتصدير التقارير بصيغة PDF فوراً.' : 'Ask the AI Assistant to generate any custom report in natural language, instantly compiled and ready for PDF export.'}
          </p>
        </div>
      </div>

      {/* AI Prompt Input Card */}
      <div className="bg-white rounded-2xl p-6 shadow-lg border border-slate-200">
        <form onSubmit={aiGenerate => handleAiGenerate(aiGenerate)} className="space-y-4">
          <div className="flex items-center gap-2">
            <div className="w-8 h-8 rounded-lg bg-emerald-50 text-emerald-600 flex items-center justify-center">
              <Bot className="w-5 h-5" />
            </div>
            <label className="text-sm font-bold text-slate-900">
              {isAr ? 'اكتب طلبك للمساعد الذكي لإنشاء أي تقرير مخصص:' : 'Type your prompt for the AI Assistant to generate a custom report:'}
            </label>
          </div>

          <div className="flex flex-col sm:flex-row gap-3">
            <input
              type="text"
              required
              value={prompt}
              onChange={(e) => setPrompt(e.target.value)}
              placeholder={isAr ? 'مثال: اعملي تقارير أرباح الشحنات المصدرة لأسواق أوروبا مع تحليل الفاقد...' : 'Example: Generate a report comparing export profits to European markets with wastage analysis...'}
              className="flex-1 px-4 py-3 border border-slate-300 rounded-xl text-sm focus:ring-2 focus:ring-emerald-500 bg-slate-50 font-medium"
            />
            <button
              type="submit"
              disabled={isGenerating}
              className="px-6 py-3 rounded-xl bg-gradient-to-r from-emerald-500 to-teal-600 hover:from-emerald-400 hover:to-teal-500 text-slate-950 font-bold text-xs uppercase tracking-wider flex items-center justify-center gap-2 shadow-lg transition-all cursor-pointer disabled:opacity-50 shrink-0"
            >
              {isGenerating ? (
                <>
                  <div className="w-4 h-4 border-2 border-slate-950 border-t-transparent rounded-full animate-spin" />
                  <span>{isAr ? 'جاري تحليل وتوليد التقرير...' : 'AI Generating...'}</span>
                </>
              ) : (
                <>
                  <Sparkles className="w-4 h-4" />
                  <span>{isAr ? 'إنشاء التقرير بالذكاء الاصطناعي' : 'Generate with AI'}</span>
                </>
              )}
            </button>
          </div>
        </form>
      </div>

      {/* Generated Report Display Area */}
      {generatedReport && (
        <div className="bg-white rounded-2xl p-6 sm:p-8 shadow-xl border border-slate-200 space-y-6">
          <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 border-b pb-4">
            <div>
              <span className="text-xs font-bold text-emerald-600 uppercase tracking-wider">{isAr ? 'تقرير مُولَّد بالذكاء الاصطناعي' : 'AI Generated Report'}</span>
              <h3 className="text-lg font-black text-slate-900 mt-0.5">{generatedReport.title}</h3>
              <p className="text-xs text-slate-500 mt-1">{generatedReport.summary}</p>
            </div>
            <button
              onClick={downloadPDF}
              className="px-4 py-2.5 rounded-xl bg-slate-900 hover:bg-slate-800 text-white font-bold text-xs flex items-center gap-2 shadow-md shrink-0 cursor-pointer"
            >
              <Download className="w-4 h-4" />
              <span>{isAr ? 'تحميل التقرير PDF' : 'Download Report PDF'}</span>
            </button>
          </div>

          <div className="overflow-x-auto">
            <table className="w-full text-xs text-start">
              <thead>
                <tr className="bg-slate-100 text-slate-700 font-bold">
                  {generatedReport.headers.map((h, i) => (
                    <th key={i} className="p-3 text-start">{h}</th>
                  ))}
                </tr>
              </thead>
              <tbody className="divide-y divide-slate-100 font-medium text-slate-800">
                {generatedReport.rows.map((row, rIdx) => (
                  <tr key={rIdx} className="hover:bg-slate-50">
                    {row.map((cell, cIdx) => (
                      <td key={cIdx} className="p-3">{cell}</td>
                    ))}
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </div>
      )}
    </div>
  );
};
